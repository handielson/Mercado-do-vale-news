const assert=require('node:assert/strict');
const {chromium}=require('playwright');
module.exports=async function verifyAccountBrowser({app,pool,mails,messages,productId,approvePayment}){
 let vite,browser;const external=[],errors=[];
 const previousOrigin=process.env.PRINT3D_LOCAL_API_ORIGIN,previousKey=process.env.PRINT3D_PUBLIC_TURNSTILE_SITE_KEY;
 try {
  await app.listen({host:'127.0.0.1',port:0});
  process.env.PRINT3D_LOCAL_API_ORIGIN=`http://127.0.0.1:${app.server.address().port}`;
  process.env.PRINT3D_PUBLIC_TURNSTILE_SITE_KEY='local-fake-sitekey';
  const {createServer}=await import('vite');
  vite=await createServer({configFile:'vite.print3d.config.ts',cacheDir:'node_modules/.vite-print3d-account-test',server:{port:0},logLevel:'error'});await vite.listen();
  const base=`http://127.0.0.1:${vite.httpServer.address().port}`;
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844}});page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>{if(new URL(route.request().url()).origin!==base){external.push(route.request().url());return route.abort();}return route.continue();});
  await page.addInitScript(()=>{window.turnstile={render:(_element,options)=>{
   if(options.sitekey!=='local-fake-sitekey'||options.action!=='print3d_auth')throw Error('Wrong captcha scope');
   setTimeout(()=>options.callback('local-captcha'),0);return 'local-widget';},remove:()=>{}};});
  const email='browser-local-account@example.test',password='Browser-local-password-123';
  await page.goto(base+'/loja-3d/conta');
  await page.getByLabel('Nome completo',{exact:true}).fill('Cliente Navegador Local');
  await page.getByLabel('E-mail',{exact:true}).fill(email);
  await page.getByLabel('Senha',{exact:true}).fill(password);
  const submitted=page.waitForResponse(r=>r.url().includes(encodeURIComponent('/print3d/auth/register'))&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Criar conta com e-mail',exact:true}).click();assert.equal((await submitted).status(),202);
  const emailMessage=mails.find(mail=>mail.to===email);assert(emailMessage);
  const destination=new URL(emailMessage.text.match(/https:\/\/[^\s]+/)[0]);
  const [[unverified]]=await pool.query('SELECT id,email_verified_at FROM print3d_customers WHERE email=?',[email]);
  assert.equal(unverified.email_verified_at,null);
  await page.goto(base+destination.pathname+destination.search);
  await page.getByRole('button',{name:'Confirmar e-mail',exact:true}).click();
  await page.getByRole('heading',{name:'E-mail confirmado',exact:true}).waitFor();
  await page.getByRole('link',{name:'Voltar à minha conta',exact:true}).click();
  await page.getByRole('button',{name:'Entrar',exact:true}).first().click();
  await page.getByLabel('E-mail',{exact:true}).fill(email);await page.getByLabel('Senha',{exact:true}).fill(password);
  await page.locator('form').getByRole('button',{name:'Entrar',exact:true}).click();
  await page.getByRole('link',{name:'Meus pedidos e pagamentos',exact:true}).waitFor();
  const token=await page.evaluate(()=>sessionStorage.getItem('print3d_customer_session_v1'));assert(token);
  await page.reload();await page.getByRole('link',{name:'Meus pedidos e pagamentos',exact:true}).waitFor();
  assert.equal(await page.getByRole('alert').count(),0);
  const [[verified]]=await pool.query('SELECT email_verified_at FROM print3d_customers WHERE id=?',[unverified.id]);assert(verified.email_verified_at);
  await page.getByRole('button',{name:'Sair da conta',exact:true}).click();
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('print3d_customer_session_v1')),null);
  await page.getByRole('button',{name:'Criar conta',exact:true}).click();
  await page.getByRole('button',{name:'WhatsApp',exact:true}).click();
  const phone='5587987654321',cpf='11144477735';
  await page.getByLabel('Nome completo',{exact:true}).fill('Cliente WhatsApp Navegador');
  await page.getByLabel('WhatsApp com DDD',{exact:true}).fill(phone);
  await page.locator('#account-cpf').fill(cpf);
  await page.getByLabel('Senha',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Enviar código',exact:true}).click();
  await page.getByRole('heading',{name:'Confirme seu WhatsApp',exact:true}).waitFor();
  const message=messages.find(value=>value.phone===phone);assert(message);
  const code=message.message.match(/\b[0-9]{6}\b/)[0];
  await page.getByLabel('Código de confirmação',{exact:true}).fill(code==='000000'?'111111':'000000');
  await page.getByRole('button',{name:'Confirmar',exact:true}).click();
  await page.getByRole('alert').waitFor();
  await page.getByLabel('Código de confirmação',{exact:true}).fill(code);
  await page.getByRole('button',{name:'Confirmar',exact:true}).click();
  await page.getByRole('heading',{name:'Conta pronta',exact:true}).waitFor();
  await page.getByText('Seu WhatsApp está confirmado para futuras encomendas.',{exact:true}).waitFor();
  const [[phoneCustomer]]=await pool.query('SELECT email,phone_verified_at,cpf_cnpj FROM print3d_customers WHERE phone=?',[phone]);
  assert.equal(phoneCustomer.email,null);assert.equal(phoneCustomer.cpf_cnpj,cpf);assert(phoneCustomer.phone_verified_at);
  for(const channel of ['WhatsApp','CPF']) {
   await page.getByRole('button',{name:'Sair da conta',exact:true}).click();
   await page.getByRole('button',{name:channel,exact:true}).click();
   if(channel==='WhatsApp')await page.getByLabel('WhatsApp com DDD',{exact:true}).fill(phone);
   else await page.locator('#account-cpf').fill(cpf);
   await page.getByLabel('Senha',{exact:true}).fill(password);
   await page.locator('form').getByRole('button',{name:'Entrar',exact:true}).click();
   await page.getByRole('heading',{name:'Conta pronta',exact:true}).waitFor();
   await page.getByText('Seu WhatsApp está confirmado para futuras encomendas.',{exact:true}).waitFor();
  }
  assert.equal(await page.getByRole('alert').count(),0);
  await page.evaluate(id=>sessionStorage.setItem('print3d_checkout_cart_v1',JSON.stringify([{product_id:id,quantity:2}])),productId);
  await page.goto(base+'/loja-3d/checkout');
  for(const [label,value] of [['CEP','56300000'],['Rua / avenida','Rua Teste'],['Número ou S/N','1'],['Bairro','Centro'],['Cidade','Petrolina'],['Estado (UF)','PE']])
   await page.getByLabel(label,{exact:true}).fill(value);
  await page.getByRole('button',{name:'Conferir produtos e entrega',exact:true}).click();
  await page.getByRole('heading',{name:'Entrega e valores',exact:true}).waitFor();
  await page.locator('input[name="delivery"]').check();
  assert.match(await page.getByTestId('initial-payment').innerText(),/10,00/);
  assert.match(await page.getByTestId('balance-payment').innerText(),/15,00/);
  await page.getByLabel('Frete inteiro agora',{exact:false}).check();
  assert.match(await page.getByTestId('initial-payment').innerText(),/15,00/);
  assert.match(await page.getByTestId('balance-payment').innerText(),/10,00/);
  await page.getByLabel('Percentual de entrada nos produtos',{exact:true}).fill('49');
  assert.equal(await page.getByRole('button',{name:'Criar pedido e continuar para pagamento',exact:true}).isDisabled(),true);
  await page.getByLabel('Percentual de entrada nos produtos',{exact:true}).fill('70');
  await page.getByLabel('Dividir o frete',{exact:false}).check();
  assert.match(await page.getByTestId('initial-payment').innerText(),/17,50/);
  assert.match(await page.getByTestId('balance-payment').innerText(),/7,50/);
  assert.equal(await page.getByLabel(/IMEI/i).count(),0);
  const creating=page.waitForResponse(r=>r.url().includes(encodeURIComponent('/print3d/checkout'))&&r.request().method()==='POST');
  const paymentLoading=page.waitForResponse(r=>decodeURIComponent(r.url()).match(/\/print3d\/orders\/[0-9a-f-]+\/payment$/)&&r.request().method()==='GET');
  await page.getByRole('button',{name:'Criar pedido e continuar para pagamento',exact:true}).click();
  const response=await creating;assert.equal(response.status(),200,await response.text());
  const {order}=await response.json();assert.equal(order.total_cents,2500);assert.equal(order.payment_schedule.initial_cents,1750);
  await page.waitForURL('**/loja-3d/pedidos');
  const paymentResponse=await paymentLoading;assert.equal(paymentResponse.status(),200,await paymentResponse.text());
  assert.equal(await page.getByRole('alert').count(),0);
  const [[persisted]]=await pool.query('SELECT o.storefront,o.customer_id,c.phone FROM orders o JOIN print3d_customers c ON c.id=o.print3d_customer_id WHERE o.id=?',[order.id]);
  assert.equal(persisted.storefront,'loja_3d');assert.equal(persisted.customer_id,null);assert.equal(persisted.phone,phone);
  const [[production]]=await pool.query('SELECT target_quantity,status FROM print3d_production_jobs WHERE order_id=?',[order.id]);
  assert.equal(production.target_quantity,2);assert.equal(production.status,'awaiting_payment');
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('print3d_checkout_cart_v1')),null);
  await require('./print3d-account-production-mysql-browser.cjs')({page,base,app,pool,orderId:order.id,phone});
  await require('./print3d-account-balance-mysql-browser.cjs')({page,base,app,pool,orderId:order.id,approvePayment});
  assert.deepEqual(external,[]);assert.deepEqual(errors,[]);
  console.log('PASS: authenticated browser checkout creates an isolated 3D order and production job without IMEI; 70% entry including proportional freight persisted in MySQL.');
  console.log('PASS: standalone browser → local proxy → real account routes → disposable MySQL; email/WhatsApp registration, verification, phone/CPF login and session reload.');
 } finally {
  if(browser)await browser.close();if(vite)await vite.close();
  if(previousOrigin===undefined)delete process.env.PRINT3D_LOCAL_API_ORIGIN;else process.env.PRINT3D_LOCAL_API_ORIGIN=previousOrigin;
  if(previousKey===undefined)delete process.env.PRINT3D_PUBLIC_TURNSTILE_SITE_KEY;else process.env.PRINT3D_PUBLIC_TURNSTILE_SITE_KEY=previousKey;
 }
};
