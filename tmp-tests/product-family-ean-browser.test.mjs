import assert from 'node:assert/strict';
import { build, preview } from 'vite';
import { chromium } from 'playwright';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const out = mkdtempSync(join(tmpdir(), 'mdv-family-ean-'));
await build({ configFile: 'vite.config.ts', root: process.cwd(), build: { outDir: out, emptyOutDir: true,
    rollupOptions: { input: 'tmp-tests/product-family-ean-preview.html' } } });
const server = await preview({ configFile: false, root: out, build: { outDir: '.' }, preview: { host: '127.0.0.1', port: 0 } });
let browser;
try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    await page.goto(`${server.resolvedUrls.local[0]}tmp-tests/product-family-ean-preview.html`);
    const input = page.getByPlaceholder('7891234567890').first();
    await input.pressSequentially('7891234567890');
    assert.equal(await input.inputValue(), '7891234567890');
    assert.equal(await page.getByTestId('ean-state').innerText(), '["7891234567890"]');
    assert.ok(Number(await page.getByTestId('render-tick').innerText()) > 0, 'A edição precisa continuar a marcar o rascunho como alterado');
    assert.deepEqual(errors, []);
    console.log('Family EAN browser typing passed');
    await page.goto(`${server.resolvedUrls.local[0]}tmp-tests/product-family-ean-preview.html?smartphone`);
    const config = page.getByRole('group', { name: 'Adicionar configuração de memória' });
    await config.getByRole('button', { name: 'Selecionar todas as cores', exact: true }).click();
    await config.getByRole('combobox', { name: 'Memória RAM', exact: true }).selectOption('8GB');
    await config.getByRole('combobox', { name: 'Armazenamento', exact: true }).selectOption('256GB');
    await page.getByRole('button', { name: 'Restaurar rascunho de teste' }).click();
    assert.equal(await config.getByRole('combobox', { name: 'Memória RAM', exact: true }).inputValue(), '8GB');
    await config.getByRole('button', { name: 'Adicionar às cores selecionadas' }).click();
    assert.equal(JSON.parse(await page.getByTestId('rows-state').textContent()).length, 2);
    await page.getByRole('button', { name: 'Editar detalhes', exact: true }).first().click();
    const smartphoneEan = page.getByPlaceholder('7891234567890').first();
    await smartphoneEan.pressSequentially('7891234567890');
    await page.getByRole('button', { name: 'Recolher detalhes' }).click();
    await config.getByRole('combobox', { name: 'Memória RAM', exact: true }).selectOption('12GB');
    await config.getByRole('combobox', { name: 'Armazenamento', exact: true }).selectOption('512GB');
    await config.getByRole('button', { name: 'Adicionar às cores selecionadas' }).click();
    await config.getByRole('button', { name: 'Adicionar às cores selecionadas' }).click();
    const state = JSON.parse(await page.getByTestId('rows-state').textContent());
    assert.equal(state.length, 4);
    assert.deepEqual(state[0].data.eans, ['7891234567890']);
    assert.deepEqual(state[2].data.eans, []);
    assert.equal(state[2].data.specs.ram, '12GB'); assert.equal(state[2].data.specs.storage, '512GB');
    assert.equal(await page.getByRole('heading', { name: 'Preços por configuração' }).count(), 1);
    const costs8 = page.getByLabel('Custo médio em estoque 8GB / 256GB', { exact: true });
    const costs12 = page.getByLabel('Custo médio em estoque 12GB / 512GB', { exact: true });
    await costs8.getByText(/1\.234,50/).waitFor();
    assert.match(await costs12.innerText(), /Sem custo de compra em estoque/);
    assert.doesNotMatch(await costs8.innerText(), /9\.999,00/, 'Usar o grupo exato retornado pela API, sem misturar versões');
    await page.evaluate(() => { window.fixtureInventoryCost = 0; });
    await page.getByRole('button', { name: 'Atualizar custo médio em estoque' }).click();
    await costs8.getByText(/R\$\s*0,00/).waitFor();
    await page.evaluate(() => { window.fixtureInventoryFailure = true; });
    await page.getByRole('button', { name: 'Atualizar custo médio em estoque' }).click();
    await page.getByRole('alert').filter({ hasText: 'Não foi possível consultar o custo médio' }).waitFor();
    assert.match(await costs8.innerText(), /Consulta indisponível/);
    await page.evaluate(() => { window.fixtureInventoryFailure = false; window.fixtureInventoryCost = 123450; });
    await page.getByRole('button', { name: 'Atualizar custo médio em estoque' }).click();
    await costs8.getByText(/1\.234,50/).waitFor();
    assert.deepEqual(errors, []);
    await page.locator('output, form > button').evaluateAll(elements => elements.forEach(element => element.style.display = 'none'));
    await page.setViewportSize({ width: 1280, height: 1100 });
    await page.screenshot({ path: join(out, 'configuracoes-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: join(out, 'configuracoes-mobile.png'), fullPage: true });
    console.log(`Visual previews: ${out}`);
    console.log('Smartphone configuration browser flow passed');
    await page.goto(`${server.resolvedUrls.local[0]}tmp-tests/product-family-ean-preview.html?smartphone&saved`);
    await page.getByLabel('Custo médio em estoque 8GB / 256GB', { exact: true }).getByText(/1\.234,50/).waitFor();
    assert.equal(await page.getByRole('region', { name: 'Preços das configurações' }).count(), 1);
    assert.equal(await page.getByRole('button', { name: 'Remover rascunho' }).count(), 0);
    assert.deepEqual(errors, []);
    console.log('Stock purchase average: new and saved variations, exact group, zero, missing data and retry passed');
} finally {
    await browser?.close();
    await server.httpServer.close();
}
